const LV_IMG_W=1600,LV_IMG_H=1304,LV_RADIUS=18;
var _lvScale=1,_lvBlinkTimer=null,_lvActiveLot=null;

function openLotView(sec,lotNo){
  if(_lvBlinkTimer){clearInterval(_lvBlinkTimer);_lvBlinkTimer=null;}
  _lvActiveLot=null;
  var title=(sec&&lotNo)?('Section '+sec+' - Lot '+lotNo):'Section 15 & 16';
  document.getElementById('lotViewTitle').textContent=title;
  document.getElementById('lotViewOverlay').style.display='flex';
  var body=document.getElementById('lotViewBody');
  if(body._lv_clean)body._lv_clean();
  var drag=false,sx,sy,sl,st;
  var onDown=function(e){drag=true;sx=e.pageX;sy=e.pageY;sl=body.scrollLeft;st=body.scrollTop;body.style.cursor='grabbing';};
  var onUp=function(){drag=false;body.style.cursor='grab';};
  var onMove=function(e){if(!drag)return;body.scrollLeft=sl-(e.pageX-sx);body.scrollTop=st-(e.pageY-sy);};
  body.addEventListener('mousedown',onDown);
  body.addEventListener('mouseleave',onUp);
  body.addEventListener('mouseup',onUp);
  body.addEventListener('mousemove',onMove);
  body._lv_clean=function(){
    body.removeEventListener('mousedown',onDown);
    body.removeEventListener('mouseleave',onUp);
    body.removeEventListener('mouseup',onUp);
    body.removeEventListener('mousemove',onMove);
  };
  body.addEventListener('touchstart',function(e){if(e.touches.length===1){sx=e.touches[0].clientX;sy=e.touches[0].clientY;sl=body.scrollLeft;st=body.scrollTop;}},{passive:true});
  body.addEventListener('touchmove',function(e){if(e.touches.length===1){body.scrollLeft=sl-(e.touches[0].clientX-sx);body.scrollTop=st-(e.touches[0].clientY-sy);}},{passive:true});
  setTimeout(function(){
    var bw=body.clientWidth,bh=body.clientHeight;
    var fit=Math.min(bw/LV_IMG_W,bh/LV_IMG_H,1);
    _lvApplyScale(fit);
    body.scrollLeft=Math.max(0,(LV_IMG_W*_lvScale-bw)/2);
    body.scrollTop=Math.max(0,(LV_IMG_H*_lvScale-bh)/2);
    if(sec&&lotNo){
      var coord=(LV_COORDS[String(sec)]||{})[String(lotNo)];
      if(coord){_lvActiveLot={sec:sec,lotNo:lotNo,coord:coord};_lvStartBlink();_lvScrollTo(coord);}
    }
  },150);
}

function _lvApplyScale(s){
  _lvScale=s;
  var inner=document.getElementById('lotViewInner');
  inner.style.transformOrigin='top left';
  inner.style.transform='scale('+s+')';
  document.getElementById('lotViewImg').style.width=LV_IMG_W+'px';
  document.getElementById('lotViewImg').style.height=LV_IMG_H+'px';
  _lvUpdateBlink();
}

function _lvUpdateBlink(){
  var blink=document.getElementById('lotBlink');
  if(!_lvActiveLot){blink.style.display='none';return;}
  var c=_lvActiveLot.coord,r=LV_RADIUS;
  blink.style.left=(c.x-r)+'px';
  blink.style.top=(c.y-r)+'px';
  blink.style.width=(r*2)+'px';
  blink.style.height=(r*2)+'px';
  blink.style.display='block';
}

function _lvStartBlink(){
  _lvUpdateBlink();
  var blink=document.getElementById('lotBlink'),vis=true;
  blink.style.opacity='1';
  if(_lvBlinkTimer)clearInterval(_lvBlinkTimer);
  _lvBlinkTimer=setInterval(function(){vis=!vis;blink.style.opacity=vis?'1':'0';},500);
  if(_lvActiveLot&&typeof showToast==='function')
    showToast('Section '+_lvActiveLot.sec+' Lot '+_lvActiveLot.lotNo+' 위치 표시 중');
}

